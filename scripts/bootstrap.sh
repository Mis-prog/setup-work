#!/bin/sh
# setup-work stage 0. POSIX sh; needs python3 (preinstalled, there is no Python mirror).
#
# Settings: <config>/bootstrap.env (KEY=VALUE, `make init` creates it), where <config> is
# $SETUP_WORK_HOME/config when SETUP_WORK_HOME is set (one persistent folder, e.g. on NFS:
# config, registries, bin, data, caches; `. $SETUP_WORK_HOME/env.sh` in every new shell),
# otherwise ~/.config/setup-work.
#  1. registries: write the corporate PyPI into pip.conf AND uv.toml (uv reads its own
#     file) and the npm registry into .npmrc.        -> `make registries`
#  2. uv: if missing, take it from SETUP_WORK_UV_ARCHIVE (path, hdfs://, https://) or
#     the corporate PyPI (SETUP_WORK_UV_FROM_PIP=1).
#  3. project venv: `uv sync` against the corporate index.  -> `make sync`
# Nothing is downloaded from public hosts. No sudo, no shell-profile edits.
#
# Usage: sh scripts/bootstrap.sh [--dry-run] [--init] [--registries-only] [--sync-only]

set -eu

UV_VERSION="0.12.13"
# sha256 of the official uv-<target>.tar.gz release files (uv 0.12.13)
SHA_aarch64_apple_darwin="7e6ddb9316acc00f2296c82ff4d99977870ee34b2f0ddcae9444d714db9364ed"
SHA_x86_64_apple_darwin="5e287ef61cb6a9b61b3a83fef124fd143e400468a7dac794230147a810e17119"
SHA_aarch64_unknown_linux_gnu="2eaa5d94f5db7b3a1a092156b9420459e42ab0217d917fe74a876309cef9b5e9"
SHA_x86_64_unknown_linux_gnu="745765a3b6e360ad76743599ae5c42e9278c7edf8bbff9fc76d05bf2623a04dd"

say() { printf '%s\n' "$*"; }
die() { say "error: $1" >&2; exit "${2:-1}"; }
expand_home() {
    case "$1" in
        "~/"*) say "$HOME/${1#"~/"}" ;;
        '$HOME/'*) say "$HOME/${1#'$HOME/'}" ;;
        *) say "$1" ;;
    esac
}

# ---- where everything lives ---------------------------------------------------
SW_HOME="${SETUP_WORK_HOME:+$(expand_home "$SETUP_WORK_HOME")}"
if [ -n "$SW_HOME" ]; then
    # pip, uv and npm read these variables, so their files and caches survive containers.
    export SETUP_WORK_HOME="$SW_HOME"
    export PIP_CONFIG_FILE="${PIP_CONFIG_FILE:-$SW_HOME/registries/pip.conf}"
    export UV_CONFIG_FILE="${UV_CONFIG_FILE:-$SW_HOME/registries/uv.toml}"
    export NPM_CONFIG_USERCONFIG="${NPM_CONFIG_USERCONFIG:-$SW_HOME/registries/npmrc}"
    export UV_CACHE_DIR="${UV_CACHE_DIR:-$SW_HOME/cache/uv}"
    export npm_config_cache="${npm_config_cache:-$SW_HOME/cache/npm}"
    export GIT_CONFIG_GLOBAL="${GIT_CONFIG_GLOBAL:-$SW_HOME/gitconfig}"
fi
CONFIG_DIR="${SETUP_WORK_USER_CONFIG_DIR:-${SW_HOME:+$SW_HOME/config}}"
CONFIG_DIR="${CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/setup-work}"
BIN_DIR="${SETUP_WORK_BIN_DIR:-${SW_HOME:+$SW_HOME/bin}}"
BIN_DIR="${BIN_DIR:-$HOME/.local/bin}"
DATA_DIR="${SW_HOME:+$SW_HOME/data}"
DATA_DIR="${DATA_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/setup-work}"


# ---- settings: KEY=VALUE lines only, never executed as shell -----------------
load_env_file() {
    [ -f "$1" ] || return 0
    say "loading settings from $1"
    while IFS= read -r line || [ -n "$line" ]; do
        case "$line" in ''|'#'*) continue ;; esac
        key=${line%%=*}
        value=${line#*=}
        case "$key" in
            *[!A-Za-z0-9_]*|[0-9]*|'') say "  skipping invalid line: $line"; continue ;;
        esac
        case "$key" in
            *TOKEN*|*SECRET*|*PASSWORD*|*API_KEY*) say "  refusing secret-like key $key"; continue ;;
        esac
        # strip optional surrounding quotes
        case "$value" in \"*\") value=${value#\"}; value=${value%\"} ;; \'*\') value=${value#\'}; value=${value%\'} ;; esac
        eval "already=\${$key+set}"
        if [ "$already" = set ]; then continue; fi  # the user's environment wins
        export "$key=$value"
        say "  $key set"
    done < "$1"
}
load_env_file "$CONFIG_DIR/bootstrap.env"

UV_VERSION="${SETUP_WORK_UV_VERSION:-$UV_VERSION}"
DRY_RUN="${SETUP_WORK_DRY_RUN:-}"
INIT=
REGISTRIES_ONLY=
SYNC_ONLY=
for arg in "$@"; do
    case "$arg" in
        --dry-run) DRY_RUN=1 ;;
        --init) INIT=1 ;;
        --registries-only) REGISTRIES_ONLY=1 ;;
        --sync-only) SYNC_ONLY=1 ;;
        *) die "unknown argument: $arg (expected --dry-run, --init, --registries-only, --sync-only)" 2 ;;
    esac
done
case "$DRY_RUN" in 1|true|yes) DRY_RUN=1 ;; *) DRY_RUN= ;; esac

run() {
    say "  \$ $*"
    [ -n "$DRY_RUN" ] && return 0
    "$@"
}

ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)

# ---- init: settings templates (+ env.sh with SETUP_WORK_HOME) -----------------------
if [ -n "$INIT" ]; then
    mkdir -p "$CONFIG_DIR"
    for f in bootstrap.env corporate.yaml harnesses.yaml; do
        if [ -e "$CONFIG_DIR/$f" ]; then say "  keep    $CONFIG_DIR/$f (already exists)"
        else cp "$ROOT/examples/corp/$f" "$CONFIG_DIR/$f" && say "  created $CONFIG_DIR/$f"; fi
    done
    if [ -n "$SW_HOME" ]; then
        { say "# Generated by \`make init\`. In every new shell / container:  . $SW_HOME/env.sh"
          say "export SETUP_WORK_HOME=\"$SW_HOME\""
          say "export PATH=\"\$SETUP_WORK_HOME/bin:\$PATH\""
          say "export PIP_CONFIG_FILE=\"\$SETUP_WORK_HOME/registries/pip.conf\""
          say "export UV_CONFIG_FILE=\"\$SETUP_WORK_HOME/registries/uv.toml\""
          say "export NPM_CONFIG_USERCONFIG=\"\$SETUP_WORK_HOME/registries/npmrc\""
          say "export UV_CACHE_DIR=\"\$SETUP_WORK_HOME/cache/uv\""
          say "export npm_config_cache=\"\$SETUP_WORK_HOME/cache/npm\""
          say "export UV_PYTHON_DOWNLOADS=never"
          say "export GIT_CONFIG_GLOBAL=\"\$SETUP_WORK_HOME/gitconfig\"   # git config --global и логин Bitbucket"
        } > "$SW_HOME/env.sh"
        say "  created $SW_HOME/env.sh"
        say "Fill in $CONFIG_DIR/*, then:  . $SW_HOME/env.sh && make bootstrap"
    else
        say "Fill in $CONFIG_DIR/*, then: make bootstrap"
    fi
    exit 0
fi

# ---- 1. registries -> pip.conf, uv.toml, .npmrc ---------------------------------
# Credentials are read from files; never printed or passed on a command line.
#   SETUP_WORK_PYPI_INDEX         https://host/path/simple
#   SETUP_WORK_PYPI_USER          user name in the index URL (default: token)
#   SETUP_WORK_PYPI_AUTH_FILE     file with the password/token for the index
#   SETUP_WORK_PYPI_TRUSTED_HOST  host pip/uv may reach without TLS verification
#   SETUP_WORK_NPM_REGISTRY       https://host/path/
#   SETUP_WORK_NPM_AUTH_FILE      file with the npm _authToken
#   SETUP_WORK_NPM_CAFILE         CA bundle for the registry (preferred over the next one)
#   SETUP_WORK_NPM_STRICT_SSL     false disables TLS verification for npm
read_secret() {
    f=$(expand_home "$1")
    [ -r "$f" ] || die "cannot read $2 file: $f" 6
    tr -d ' \t\r\n' < "$f"
}

UV_TOML="${UV_CONFIG_FILE:-${XDG_CONFIG_HOME:-$HOME/.config}/uv/uv.toml}"

setup_pypi() {
    [ -n "${SETUP_WORK_PYPI_INDEX:-}" ] || return 0
    conf="${PIP_CONFIG_FILE:-${XDG_CONFIG_HOME:-$HOME/.config}/pip/pip.conf}"
    auth="${SETUP_WORK_PYPI_AUTH_FILE:+$(expand_home "$SETUP_WORK_PYPI_AUTH_FILE")}"
    say "configuring PyPI $SETUP_WORK_PYPI_INDEX in $conf and $UV_TOML${auth:+ (credentials from $auth)}"
    [ -n "$DRY_RUN" ] && return 0
    if [ -n "$auth" ] && [ ! -r "$auth" ]; then die "cannot read the PyPI auth file: $auth" 6; fi
    py=$(command -v python3 || true)
    [ -n "$py" ] || die "python3 is required (it must be preinstalled)" 3
    # pip.conf keeps your other settings; uv.toml is owned by setup-work. Token stays off argv.
    "$py" -I -c '
import configparser, json, os, sys
from urllib.parse import quote, urlsplit, urlunsplit
conf, uv_toml, index, user, auth, trusted = sys.argv[1:7]
if auth:
    with open(auth) as fh:
        token = "".join(fh.read().split())
    u = urlsplit(index)
    host = u.hostname + (":%d" % u.port if u.port else "")
    netloc = quote(user, safe="") + ":" + quote(token, safe="") + "@" + host
    index = urlunsplit((u.scheme, netloc, u.path, u.query, u.fragment))

def write(path, text):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = path + ".setup-work.tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    os.replace(tmp, path)

cp = configparser.RawConfigParser()
cp.read(conf)
if not cp.has_section("global"):
    cp.add_section("global")
cp.set("global", "index-url", index)
if trusted:
    cp.set("global", "trusted-host", trusted)
import io
buf = io.StringIO()
cp.write(buf)
write(conf, buf.getvalue())

MARK = "# managed by setup-work"
if os.path.exists(uv_toml) and not open(uv_toml).read().startswith(MARK):
    sys.exit("error: %s exists and was not written by setup-work; move it away first" % uv_toml)
lines = [MARK + " (make registries): edit bootstrap.env instead", "python-downloads = \"never\""]
if trusted:
    lines.append("allow-insecure-host = [%s]" % json.dumps(trusted))
lines += ["", "[[index]]", "name = \"corp\"", "url = %s" % json.dumps(index), "default = true", ""]
write(uv_toml, "\n".join(lines))
' "$conf" "$UV_TOML" "$SETUP_WORK_PYPI_INDEX" "${SETUP_WORK_PYPI_USER:-token}" "$auth" \
        "${SETUP_WORK_PYPI_TRUSTED_HOST:-}" || die "failed to write $conf / $UV_TOML" 1
}

setup_npm() {
    [ -n "${SETUP_WORK_NPM_REGISTRY:-}" ] || return 0
    rc="${NPM_CONFIG_USERCONFIG:-$HOME/.npmrc}"
    reg="$SETUP_WORK_NPM_REGISTRY"
    case "$reg" in */) ;; *) reg="$reg/" ;; esac
    key="//${reg#*://}:_authToken"
    auth="${SETUP_WORK_NPM_AUTH_FILE:+$(expand_home "$SETUP_WORK_NPM_AUTH_FILE")}"
    cafile="${SETUP_WORK_NPM_CAFILE:+$(expand_home "$SETUP_WORK_NPM_CAFILE")}"
    strict="${SETUP_WORK_NPM_STRICT_SSL:-}"
    say "configuring npm registry $reg in $rc${auth:+ (token from $auth)}"
    [ -n "$DRY_RUN" ] && return 0
    tok=
    [ -n "$auth" ] && tok=$(read_secret "$auth" "npm auth")
    mkdir -p "$(dirname -- "$rc")"
    tmp="$rc.setup-work.tmp"
    # Replace only the keys managed here; everything else in .npmrc is kept.
    ( umask 077
      {
        if [ -f "$rc" ]; then
            awk -v k="$key=" 'index($0, "registry=") != 1 && index($0, k) != 1 &&
                index($0, "cafile=") != 1 && index($0, "strict-ssl=") != 1' "$rc"
        fi
        say "registry=$reg"
        if [ -n "$tok" ]; then say "$key=$tok"; fi
        if [ -n "$cafile" ]; then say "cafile=$cafile"; fi
        if [ -n "$strict" ]; then say "strict-ssl=$strict"; fi
      } > "$tmp" ) && mv "$tmp" "$rc" || die "failed to write $rc" 1
}

if [ -z "$SYNC_ONLY" ]; then
    setup_pypi
    setup_npm
fi
if [ -n "$REGISTRIES_ONLY" ]; then
    say "registries configured"
    exit 0
fi

# ---- 2. uv ---------------------------------------------------------------------
find_uv() {
    if command -v uv >/dev/null 2>&1; then command -v uv; return 0; fi
    if [ -x "$BIN_DIR/uv" ]; then say "$BIN_DIR/uv"; return 0; fi
    return 1
}

uv_target() {
    os=$(uname -s); arch=$(uname -m)
    case "$arch" in
        x86_64|amd64) arch=x86_64 ;;
        arm64|aarch64) arch=aarch64 ;;
        *) die "unsupported architecture: $arch" 4 ;;
    esac
    case "$os" in
        Darwin) say "${arch}-apple-darwin" ;;
        Linux)
            if ldd --version 2>&1 | grep -qi musl; then
                die "musl libc is not covered by the pinned uv build; install uv manually" 4
            fi
            say "${arch}-unknown-linux-gnu" ;;
        *) die "unsupported OS: $os" 4 ;;
    esac
}

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
    elif command -v shasum >/dev/null 2>&1; then shasum -a 256 "$1" | cut -d' ' -f1
    else die "need sha256sum or shasum to verify downloads" 3
    fi
}

fetch() {  # url dest
    if command -v curl >/dev/null 2>&1; then
        run curl --proto '=https' --tlsv1.2 -fL --retry 3 --connect-timeout 20 -o "$2" "$1"
    elif command -v wget >/dev/null 2>&1; then
        run wget --https-only -q -O "$2" "$1"
    else
        die "need curl or wget for an https:// SETUP_WORK_UV_ARCHIVE (or use a path, hdfs:// or SETUP_WORK_UV_FROM_PIP=1)" 3
    fi
}

link_uv() {  # dir containing uv and uvx
    run mkdir -p "$BIN_DIR"
    for b in uv uvx; do
        [ -e "$1/$b" ] || [ -n "$DRY_RUN" ] || continue
        link="$BIN_DIR/$b"
        if [ -e "$link" ] && [ ! -L "$link" ]; then
            die "$link exists and is not a symlink; refusing to overwrite"
        fi
        run ln -sfn "$1/$b" "$link"
    done
}

install_uv_archive() {
    target=$(uv_target)
    var="SHA_$(say "$target" | tr '-' '_')"
    eval "expected=\${$var:-}"
    expected="${SETUP_WORK_UV_SHA256:-$expected}"
    [ -n "$expected" ] || die "no pinned checksum for $target" 4
    dest_dir="$DATA_DIR/tools/uv/$UV_VERSION"
    archive="$DATA_DIR/tools/downloads/uv-${UV_VERSION}-${target}.tar.gz"
    run mkdir -p "$DATA_DIR/tools/downloads" "$dest_dir"
    if [ -f "$archive" ] && [ "$(sha256_of "$archive")" = "$expected" ]; then
        say "  using cached $archive"
    else
        src="${SETUP_WORK_UV_ARCHIVE:-}"
        case "$src" in
            https://*) fetch "$src" "$archive.part" ;;
            hdfs:*|viewfs:*)
                command -v "${SETUP_WORK_HDFS_CLI:-hdfs}" >/dev/null 2>&1 || die "hdfs client not found" 3
                if command -v klist >/dev/null 2>&1 && ! klist -s; then
                    die "no valid Kerberos ticket: run kinit first" 1
                fi
                rm -f "$archive.part"
                run "${SETUP_WORK_HDFS_CLI:-hdfs}" dfs -get "$src" "$archive.part" ;;
            /*) run cp "$src" "$archive.part" ;;
            *) die "SETUP_WORK_UV_ARCHIVE must be an absolute path, hdfs:// or https:// URI" 2 ;;
        esac
        if [ -z "$DRY_RUN" ]; then
            got=$(sha256_of "$archive.part")
            if [ "$got" != "$expected" ]; then
                rm -f "$archive.part"
                die "checksum mismatch for uv archive (expected $expected, got $got); set SETUP_WORK_UV_SHA256 for a custom build"
            fi
            mv "$archive.part" "$archive"
        fi
    fi
    run tar -xzf "$archive" -C "$dest_dir"
    link_uv "$dest_dir/uv-$target"
}

install_uv_pip() {
    py=$(command -v python3 || true)
    [ -n "$py" ] || die "SETUP_WORK_UV_FROM_PIP=1 needs python3 with pip" 3
    target="$DATA_DIR/tools/uv-pip/$UV_VERSION"
    say "installing uv==$UV_VERSION from the corporate PyPI into $target"
    run "$py" -m pip install --disable-pip-version-check --no-deps --target "$target" "uv==$UV_VERSION"
    link_uv "$target/bin"
}

if UV=$(find_uv); then
    say "uv: $UV ($("$UV" --version 2>/dev/null || say unknown))"
elif [ -n "$SYNC_ONLY" ]; then
    die "uv not found. Run: make bootstrap   (or sh scripts/bootstrap.sh)" 3
else
    say "uv not found: installing uv $UV_VERSION into $BIN_DIR"
    use_pip=
    case "${SETUP_WORK_UV_FROM_PIP:-}" in 1|true|yes) use_pip=1 ;; esac
    if [ -n "${SETUP_WORK_UV_ARCHIVE:-}" ]; then
        install_uv_archive
    elif [ -n "$use_pip" ]; then
        install_uv_pip
    else
        die "no corporate source for uv: set SETUP_WORK_UV_ARCHIVE (path, hdfs://, https://) or SETUP_WORK_UV_FROM_PIP=1 in $CONFIG_DIR/bootstrap.env (make init creates it)" 3
    fi
    UV="$BIN_DIR/uv"
    case ":$PATH:" in
        *":$BIN_DIR:"*) ;;
        *) say ""
           say "note: $BIN_DIR is not on PATH. setup-work does not edit shell startup files."
           if [ -n "$SW_HOME" ]; then say "      run:  . $SW_HOME/env.sh"
           else say "      add this to your shell profile:  export PATH=\"$BIN_DIR:\$PATH\""; fi ;;
    esac
fi

# ---- 3. project environment -----------------------------------------------------
# uv.lock records pypi.org URLs, which are not reachable here: `uv sync` (not --frozen)
# re-resolves against the corporate index from uv.toml, keeping the locked versions.
# Without an index uv would go to pypi.org, so stop instead.
UV_PYTHON_DOWNLOADS="${UV_PYTHON_DOWNLOADS:-never}"   # there is no Python mirror
export UV_PYTHON_DOWNLOADS
if [ -z "${UV_DEFAULT_INDEX:-}${UV_INDEX_URL:-}" ] && ! grep -qs '^\[\[index\]\]' "$UV_TOML"; then
    die "no corporate PyPI configured: set SETUP_WORK_PYPI_INDEX in $CONFIG_DIR/bootstrap.env, then make registries" 2
fi
say "creating project environment (uv sync, uv.lock re-resolved against the corporate index)"
if [ -n "$DRY_RUN" ]; then
    say "  \$ $UV sync   (in $ROOT)"
else
    (cd "$ROOT" && "$UV" sync --quiet) \
        || die "uv sync failed; check that Python >= 3.11 is installed (uv does not download it) and the index in $UV_TOML" 1
    mkdir -p "$ROOT/.venv" && touch "$ROOT/.venv/.setup-work-synced"
fi
say "stage-0 bootstrap complete"
